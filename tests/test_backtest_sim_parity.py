"""
Pin the Python backtest_sim engine against golden outputs generated by the
real static/js/backtester.js.

Unlike tests/test_formula_parity.py (where Python is the source of truth and
the golden is regenerated by re-running the Python evaluator), the JS
backtester is the source of truth here: `static/js/backtester.js` is the one
prior implementation of Full-Simulation semantics, and `carrac/backtest_sim.py`
is a port of it. The golden (tests/golden/backtest_sim/expected.json) is
produced by running the REAL JS engine — see
tests/golden/backtest_sim/regenerate.mjs.

Every case here therefore runs the Python engine with `gapAwareFills: False`
(the faithful/JS-exact fill mode) — this test is only about "did the port
reproduce backtester.js correctly", not about the gap-fill
divergence (that's covered by dedicated unit tests in
tests/test_backtest_sim.py, since it's a Python-only behaviour the JS engine
has no equivalent of).

Drift here means the Python port's semantics changed relative to the JS
engine — if that's intentional (the JS engine itself changed), regenerate
with `node tests/golden/backtest_sim/regenerate.mjs`.

Tolerance: 1e-4 absolute on price/pnl-scale numbers. Both engines do the same
float64 arithmetic in the same order, so the two languages should agree to
much tighter precision than that in practice; the looser bound only absorbs
the golden's 6-decimal-place rounding.
"""

import json
import math
from pathlib import Path

import pytest

from carrac.backtest_sim import run_backtest

GOLDEN_DIR = Path(__file__).parent / 'golden' / 'backtest_sim'
TOL = 1e-4


def _load():
    fixtures = json.loads((GOLDEN_DIR / 'fixtures.json').read_text())
    expected = json.loads((GOLDEN_DIR / 'expected.json').read_text())
    return fixtures, expected


def _approx(actual, golden, label):
    if golden is None:
        assert actual is None, f'{label}: expected None, got {actual}'
        return
    if isinstance(golden, str):
        # JSON can't hold +-Infinity; the regenerate script marks it as a string.
        if golden == 'Infinity':
            assert actual == math.inf, f'{label}: expected +inf, got {actual}'
            return
        if golden == '-Infinity':
            assert actual == -math.inf, f'{label}: expected -inf, got {actual}'
            return
        assert actual == golden, f'{label}: expected {golden!r}, got {actual!r}'
        return
    if isinstance(golden, bool) or golden is None:
        assert actual == golden, f'{label}: expected {golden}, got {actual}'
        return
    if isinstance(golden, (int, float)):
        assert actual is not None and not (isinstance(actual, float) and math.isnan(actual)), (
            f'{label}: expected {golden}, got {actual}'
        )
        assert abs(float(actual) - float(golden)) < TOL, f'{label}: expected {golden}, got {actual}'
        return
    assert actual == golden, f'{label}: expected {golden!r}, got {actual!r}'


def _check_trade(actual, golden, idx, case_id):
    for key in ('entryBar', 'exitBar', 'direction', 'bars', 'exitReason', 'regime'):
        assert actual[key] == golden[key], (
            f'{case_id} trade {idx} field {key}: got {actual[key]!r}, golden {golden[key]!r}'
        )
    for key in ('entryPrice', 'exitPrice', 'pnl', 'pnlPercent', 'fundingCost'):
        _approx(actual[key], golden[key], f'{case_id} trade {idx} {key}')


def _check_stats_block(actual, golden, case_id, block_name):
    if golden is None:
        assert actual is None, f'{case_id} {block_name}: expected None, got {actual}'
        return
    assert actual is not None, f'{case_id} {block_name}: expected a stats dict, got None'
    for key, golden_val in golden.items():
        assert key in actual, f'{case_id} {block_name}: missing key {key!r}'
        _approx(actual[key], golden_val, f'{case_id} {block_name}.{key}')


@pytest.mark.parametrize('case_idx', range(6))
def test_backtest_sim_matches_js_golden(case_idx):
    fixtures, expected = _load()
    ohlcv_by_name = {f['name']: f for f in fixtures['ohlcv_fixtures']}
    case = fixtures['cases'][case_idx]
    golden = expected['results'][case_idx]
    assert golden['id'] == case['id']

    ohlcv = ohlcv_by_name[case['fixture']]
    config = dict(case['config'])
    config['gapAwareFills'] = False  # faithful mode — must match the JS engine exactly

    result = run_backtest(config, ohlcv)

    assert result['error'] == golden['error'], (
        f"{case['id']}: error mismatch — got {result['error']!r}, golden {golden['error']!r}"
    )
    if golden['error']:
        return

    assert len(result['trades']) == len(golden['trades']), (
        f"{case['id']}: trade count — got {len(result['trades'])}, golden {len(golden['trades'])}"
    )
    for i, (actual_t, golden_t) in enumerate(zip(result['trades'], golden['trades'])):
        _check_trade(actual_t, golden_t, i, case['id'])

    assert len(result['equity']) == len(golden['equity']), f"{case['id']}: equity curve length mismatch"
    for i, (a, e) in enumerate(zip(result['equity'], golden['equity'])):
        _approx(a, e, f"{case['id']} equity[{i}]")

    _check_stats_block(result['stats'], golden['stats'], case['id'], 'stats')

    if golden['statsRegime'] is None:
        assert result['statsRegime'] is None, f"{case['id']}: expected statsRegime None"
    else:
        for block in ('favorable', 'unfavorable', 'unknown'):
            _check_stats_block(result['statsRegime'][block], golden['statsRegime'][block], case['id'], f'statsRegime.{block}')


def test_all_golden_cases_present():
    fixtures, expected = _load()
    assert len(fixtures['cases']) == len(expected['results'])
    assert {c['id'] for c in fixtures['cases']} == {r['id'] for r in expected['results']}
