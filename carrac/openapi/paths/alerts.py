def _alert_kind_paths():
    paths = {}
    for path, op_id, summary, description, min_tier, props, required in _ALERT_KINDS:
        schema = {'type': 'object', 'additionalProperties': False, 'properties': props}
        if required:
            schema['required'] = required
        op = {
            'tags': [_TAG],
            'summary': summary,
            'description': description + ' Needs a delivery channel first, see `createAlert`.',
            'operationId': op_id,
            'security': _AUTH,
            'requestBody': {'required': True, 'content': {'application/json': {'schema': schema}}},
            'responses': {
                '201': {
                    'description': 'Alert created',
                    'content': {'application/json': {'schema': {
                        'type': 'object',
                        'properties': {'alert': {'$ref': '#/components/schemas/Alert'}},
                    }}},
                },
                '400': {'description': 'Invalid body, or no delivery channel configured yet', 'content': _ERROR_BODY},
                **_ERR,
            },
        }
        if min_tier:
            op['x-min-tier'] = min_tier
        paths[path] = {'post': op}
    return paths


